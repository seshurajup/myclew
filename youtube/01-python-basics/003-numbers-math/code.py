x = 10
y = 3

print(x + y)
print(x - y)
print(x * y)
print(x / y)
print(x // y)
print(x % y)
print(x ** y)

# built-in functions for common math tasks
print(abs(-7))
print(round(3.14159, 2))
print(max(x, y), min(x, y))

# Python auto-promotes int to float when needed
print(10 / 2)
print(type(10 / 2))
